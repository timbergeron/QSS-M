"""Exercise classic sky, alias-cache flushes, pending video restarts and game changes.

Usage: python3 Misc/stress/test_live_texture_lifecycle.py [binary] [id1-assets]
Uses the fixture generated by test_live_texture_mode.py and real offscreen GL.
"""
from pathlib import Path
import argparse
import json
import os
import re
import struct
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[2]
WORK = ROOT / '.codex-build/live-textures'
WORK.mkdir(parents=True, exist_ok=True)
(WORK / 'tmp').mkdir(exist_ok=True)
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('binary', nargs='?', type=Path, default=ROOT / 'Quake/quakespasm')
parser.add_argument('assets', nargs='?', type=Path, default=ROOT / '.codex-build/beachvolley-md3-verification/quake/id1')
parser.add_argument('--legacy', action='store_true')
parser.add_argument('--sanitizers', action='store_true', help='fail on ASan/UBSan errors in an instrumented binary; disable exit leak checks')
args = parser.parse_args()
fixture = Path(json.loads((WORK / 'report.json').read_text())['run']) / 'id1'
run = Path(tempfile.mkdtemp(prefix='lifecycle-', dir=WORK))
game, addon = run / 'id1', run / 'audit'
game.mkdir()
addon.mkdir()
for name in ('pak0.pak', 'pak1.pak'):
    (game / name).symlink_to((args.assets / name).resolve())
for name in ('textures', 'progs', 'gfx'):
    (game / name).symlink_to((fixture / name).resolve())
(addon / 'gfx').mkdir()
(addon / 'gfx/conchars.tga').write_bytes(
    struct.pack('<BBBHHBHHHHBB', 0, 0, 2, 0, 0, 0, 0, 0, 512, 256, 32, 8)
    + bytes((80, 120, 240, 255)) * (512 * 256))

config = ('cl_demoreel 0\ncl_web_download_url ""\ncl_web_download_url2 ""\n'
          'host_maxfps 144\nvid_vsync 0\ndeveloper 1\ncl_pong 0\n'
          'gl_load24bit 0\ngl_load24bit_hud 1\ngl_load24bit_skins 1\n'
          'r_replacemodels "md3"\nr_fastsky 0\nr_drawviewmodel 1\n')
if args.legacy:
    config += 'tex_parallel 0\nr_scenecache 0\n'
for directory in (game, addon):
    (directory / 'config.cfg').write_text(config)
    (directory / 'autoexec.cfg').write_text('')
    # Game switches queue these scripts; keep them controlled and avoid
    # restarting the test through the id1 fallback autoexec.
    (directory / 'quake.rc').write_text('exec config.cfg\nstuffcmds\n')
    (directory / 'server.cfg').write_text('')

wait = 'wait\n' * 12
commands = config + 'map start\n' + wait + 'cmd pext\n' + wait * 8 + 'pause\n' + wait
commands += 'sky ""\nfog 0.12 0.2 0.3 0.4\nr_skyfog 0.37\n' + wait
commands += 'echo LIFE_ORIGINAL\nimagelist\nsave lifecycle_before\n' + wait
commands += 'gl_load24bit 1\n' + wait + 'echo LIFE_EXTERNAL\nimagelist\nsave lifecycle_external\nr_skyfog\nfog\n' + wait
commands += 'gl_load24bit 0\n' + wait + 'echo LIFE_RESTORED\nimagelist\nsave lifecycle_after\nr_skyfog\nfog\n' + wait
# An alias header may disappear before the deferred model refresh runs. Its
# next renderer lookup must rebuild in the new mode without stale references.
commands += 'gl_load24bit 1\nflush\n' + wait + 'echo LIFE_FLUSH\nimagelist\n' + wait
commands += 'echo LIFE_VIDEO_BEGIN\ntex_verify 1\ngl_load24bit 0\nvid_unlock\nvid_width 344\nvid_restart\n' + wait * 2
commands += 'echo LIFE_VIDEO_END\nimagelist\ntex_verify 0\nr_skyfog\nfog\n' + wait
# The first switch adopts a higher-priority font. The return to id1 must drop
# it even though both games use the same relative filename for the texture.
commands += 'gl_load24bit 1\ngame audit\n' + wait + 'gl_load24bit 1\nmap start\n' + wait + 'cmd pext\n' + wait * 8
commands += 'echo LIFE_ADDON\nimagelist\n' + wait
commands += 'gl_load24bit 0\ngame id1\n' + wait + 'gl_load24bit 1\nmap start\n' + wait + 'cmd pext\n' + wait * 8
commands += 'echo LIFE_RETURN\nimagelist\n' + wait + 'echo LIFE_FINISHED\ntoggleconsole\nquit\n'
(game / 'lifecycle.cfg').write_text(commands)
logpath = run / 'engine.log'
environment = {**os.environ, 'SDL_VIDEO_DRIVER': 'offscreen', 'LIBGL_ALWAYS_SOFTWARE': '1',
               'TMPDIR': str(WORK / 'tmp'), 'XDG_CACHE_HOME': str(WORK / 'cache')}
if args.sanitizers:
    environment['ASAN_OPTIONS'] = 'detect_leaks=0:abort_on_error=1'
    environment['UBSAN_OPTIONS'] = 'halt_on_error=1:print_stacktrace=1'
print(f'Running texture lifecycle checks: {run}', flush=True)
with logpath.open('w') as log:
    result = subprocess.run(
        [str(args.binary.resolve()), '-basedir', str(run), '-nohome', '-window', '-width', '320',
         '-height', '240', '-nosound', '-nojoy', '-nomouse', '-nolan', '-noipx', '-noquakeimport',
         *(['-novbo'] if args.legacy else []), '+exec', 'lifecycle.cfg'],
        cwd=run, env=environment,
        stdout=log, stderr=subprocess.STDOUT, timeout=120)
text = logpath.read_text(errors='replace')
assert result.returncode == 0 and 'LIFE_FINISHED' in text, text[-6000:]
assert not re.search(r'TexMgr_FreeTexture: not found|invalid source|Host_Error|Sys_Error|Segmentation|AddressSanitizer|runtime error:', text), text[-6000:]


def stage(label):
    chunk = re.split(label + r'\s*\n', text, maxsplit=1)[1].split('LIFE_', 1)[0]
    return [(int(w), int(h), name.strip()) for w, h, name in
            re.findall(r'^\s+(\d+) x\s*(\d+) (.+)$', chunk, re.M)]


def save(name):
    data = (game / 'saves' / (name + '.sav')).read_text()
    return re.sub(r'^"frametime" "[^"]*"$', '', data, flags=re.M)


def font(label):
    return next((w, h) for w, h, name in stage(label) if name == 'gfx.wad:conchars')


assert save('lifecycle_before') == save('lifecycle_external') == save('lifecycle_after'), 'live refresh changed saved gameplay'
assert sorted(stage('LIFE_ORIGINAL')) == sorted(stage('LIFE_RESTORED')), 'classic sky/texture records did not restore'
assert any(name == 'maps/start.bsp:sky1_front' for _, _, name in stage('LIFE_ORIGINAL')), 'classic sky fixture missing'
assert any(name == 'textures/start/sky1_front' for _, _, name in stage('LIFE_EXTERNAL')), 'external classic sky did not load'
assert (128, 128, 'progs/v_shot.mdl_0') in stage('LIFE_FLUSH'), 'flushed viewmodel did not adopt the new mode'
assert not any(name == 'progs/v_shot.mdl_0' for _, _, name in stage('LIFE_VIDEO_END')), 'pending video restart kept the old viewmodel mode'
video = text.split('LIFE_VIDEO_BEGIN', 1)[1].split('LIFE_VIDEO_END', 1)[0]
assert len(re.findall(r'^texhash (?:maps/|textures/|progs/)', video, re.M)) > 100, 'video restart did not upload world/model images'
assert len(re.findall(r'"r_skyfog" is "0\.37"', text)) == 3, 'live refresh/restart changed sky fog'
for component, value in [('density', '0.120000'), ('red', '0.200000'), ('green', '0.300000'), ('blue', '0.400000')]:
    assert len(re.findall('"' + component + '" is "' + re.escape(value) + '"', text)) == 3, 'live refresh/restart changed fog'
assert font('LIFE_ADDON') == (512, 256) and font('LIFE_RETURN') == (256, 256), 'game switch retained the wrong font source'
assert len(re.findall(r'SV_SpawnServer total:', text)) == 3, 'texture switches unexpectedly reloaded the map'
report = {'result': 'PASS', 'legacy': args.legacy, 'sanitizers': args.sanitizers, 'binary': str(args.binary.resolve()), 'run': str(run),
          'checks': ['classic sky without a skybox', 'saved gameplay unchanged', 'fog/sky fog preserved',
                     'alias flush with pending mode change', 'video restart with pending mode change',
                     'game changes and higher-priority UI source', 'only explicit maps spawn servers']}
name = 'report-lifecycle' + ('-legacy' if args.legacy else '') + ('-sanitized' if 'sanitized' in str(args.binary) else '') + '.json'
(WORK / name).write_text(json.dumps(report, indent=2) + '\n')
print(json.dumps(report, indent=2))
